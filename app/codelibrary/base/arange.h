#ifndef CODELIBRARY_BASE_ARANGE_H_
#define CODELIBRARY_BASE_ARANGE_H_

#include <iterator>

#include "codelibrary/base/log.h"

namespace cl {

/**
 * Generate evenly spaced values within a given interval. Similar to NumPy's
 * arange().
 *
 * The `Arange` class allows for the creation of an iterable range of values
 * that are evenly spaced between a specified 'start' and 'end' value.
 * This class is templated to support various numeric types (e.g., int, float,
 * double) and provides an iterator for easy traversal of the generated
 * sequence.
 *
 * The sequence generated by the `Arange` class is defined as:
 *
 *  - start: Inclusive starting point of the sequence.
 *  - end: Exclusive endpoint of the sequence.
 *  - step: The increment between each value in the sequence.
 *
 * Example usage:
 *
 *   Arange<double> arange(0.0, 1.0, 0.2);
 *   for (double value : arange) {
 *       std::cout << value << " "; // Outputs: 0.0 0.2 0.4 0.6 0.8
 *   }
 *
 * The sequence can accommodate both positive and negative step sizes,
 * making it versatile for generating both ascending and descending sequences.
 */
template <typename T>
class ArangeIterator {
public:
    class Iterator {
    public:
        using iterator_category = std::input_iterator_tag;
        using value_type = T;
        using difference_type = std::ptrdiff_t;
        using pointer = T*;
        using reference = T&;

        Iterator(const T& current, const T& end, const T& step)
            : current_(current), step_(step), end_(end) {}

        Iterator& operator++() {
            if (step_ > 0) {
                if (current_ >= end_ - step_)
                    current_ = end_;
                else
                    current_ += step_;
            } else {
                if (current_ <= end_ - step_)
                    current_ = end_;
                else
                    current_ += step_;
            }
            return *this;
        }

        const T& operator*() const {
            return current_;
        }

        bool operator==(const Iterator& other) const {
            return current_ == other.current_;
        }

        bool operator!=(const Iterator& other) const {
            return !(*this == other);
        }

    private:
        T current_;
        T step_;
        T end_;
    };

    /**
     * Construct linspace from [start, end) with the specific step size.
     */
    ArangeIterator(const T& start, const T& end, const T& step)
        : start_(start), end_(end), step_(step) {
        CHECK(step != 0);

        if (step > 0)
            CHECK(start <= end);
        else
            CHECK(start >= end);
    }

    Iterator begin() const {
        return Iterator(start_, end_, step_);
    }

    Iterator end() const {
        return Iterator(end_, end_, step_);
    }

private:
    T start_; // The starting value of the sequence.
    T end_;   // The end value of the sequence (exclusive).
    T step_;  // The step size for increments.
};

inline ArangeIterator<int> Arange(int n) {
    CHECK(n >= 0);

    return ArangeIterator<int>(0, n, 1);
}

inline ArangeIterator<int> Arange(int start, int end) {
    return ArangeIterator<int>(start, end, 1);
}

template <typename T>
ArangeIterator<T> Arange(const T& start, const T& end, const T& step) {
    return ArangeIterator<T>(start, end, step);
}

} // namespace cl

#endif // CODELIBRARY_BASE_ARANGE_H_
